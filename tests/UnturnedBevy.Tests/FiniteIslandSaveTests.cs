    [Test] public void GroundSidecarsPreservePaintHolesAndClearStaleMask()
    {
        var surface=Flat();
        for(int x=0;x<surface.Width;x++)for(int z=0;z<surface.Height;z++)surface.Grid[x,z]=.5f+x*.00001f-z*.00002f;
        for(int x=0;x<surface.Width-1;x++)for(int z=0;z<surface.Height-1;z++)surface.Layers[x,z]=(byte)(x==0?5:2);
        surface.SetHole(0,0,true);surface.SetHole(0,7,true);surface.SetHole(0,8,true);
        Assert.That(surface.SetHole(-1,0,true),Is.False);
        surface.SaveHeightmap(At("height.bin"));
        var loaded=Flat();
        Assert.That(loaded.LoadHeightmap(At("height.bin")),Is.True);
        Assert.That(loaded.HoleCount,Is.EqualTo(3));
        Assert.That(loaded.IsHole(0,0)&&loaded.IsHole(0,7)&&loaded.IsHole(0,8),Is.True);
        Assert.That(loaded.IsHole(0,6),Is.False);
        Assert.That(loaded.Layers,Is.EqualTo(surface.Layers));
        Assert.That(loaded.Grid,Is.EqualTo(surface.Grid));
        loaded.SaveHeightmap(At("restored.bin"));
        foreach(string ext in new[]{"",".holes",".splat"})
            Assert.That(File.ReadAllBytes(At("restored.bin"+ext)),Is.EqualTo(File.ReadAllBytes(At("height.bin"+ext))));
        loaded.SetHole(0,0,false);loaded.SetHole(0,7,false);loaded.SetHole(0,8,false);
        loaded.SaveHeightmap(At("height.bin"));
        Assert.That(File.Exists(At("height.bin.holes")),Is.False,"filling must delete old on-disk holes");
        surface.LoadHeightmap(At("height.bin"));
        Assert.That(surface.HoleCount,Is.Zero,"missing sidecar clears previous map mask");
        File.WriteAllBytes(At("height.bin.holes"),new byte[]{1,0,0,0,1,0,0,0,1});
        surface.LoadHoles(At("height.bin.holes"));
        Assert.That(surface.HoleCount,Is.Zero,"wrong-sized sidecar is ignored");
        using(var w=new BinaryWriter(File.Create(At("height.bin.holes")))){w.Write(256);w.Write(256);w.Write((byte)255);}
        surface.LoadHoles(At("height.bin.holes"));
        Assert.That(surface.HoleCount,Is.Zero,"truncation cannot leave a partially installed mask");
    }

    [Test] public void RiverRecipesReopenWithoutCompoundingOrDroppingLegacySegments()
    {
        using(var w=new BinaryWriter(File.Create(At("river.bin"))))
        {
            w.Write(2);w.Write(2);
            for(int i=0;i<2;i++)
            {
                w.Write(80f+i*20);w.Write(0f);w.Write(-80f);
                w.Write(100f+i*20);w.Write(0f);w.Write(-80f);
                w.Write(8f);w.Write(4f);
            }
            w.Write(1);w.Write(1);w.Write(1f);w.Write(2f);w.Write(3f);
        }
        var surface=Flat();surface.LoadRivers(At("river.bin"));
        Assert.That(surface.RiverCount,Is.EqualTo(1),"source v2 chains equal-width connected segments");
        Assert.That(surface.Rivers[0].Anchors.Count,Is.EqualTo(3));
        Assert.That(surface.RiverCutWorld(100,-80),Is.EqualTo(4));
        Assert.That(surface.RiverCutWorld(100,-88),Is.EqualTo(1.4f));
        Assert.That(surface.RiverCutWorld(100,-101),Is.Zero);
        float sample=surface.SampleHeight(100,-80);
        surface.SaveHeightmap(At("height.bin"));
        surface.LoadHeightmap(At("height.bin"));surface.LoadHeightmap(At("height.bin"));
        Assert.That(surface.SampleHeight(100,-80),Is.EqualTo(sample),"cuts remain derived from recipe, not baked twice");
        Assert.That(BitConverter.ToInt32(File.ReadAllBytes(At("height.bin.rivers"))),Is.EqualTo(3));
        surface.LoadRivers(At("absent"));surface.SaveHeightmap(At("height.bin"));
        Assert.That(File.Exists(At("height.bin.rivers")),Is.False,"empty rivers remove stale recipe");
        Assert.That(surface.SampleHeight(100,-80),Is.EqualTo(sample+4));
    }
