    }
    [TearDown] public void Cleanup() => Directory.Delete(temporary,true);
    static string Hash(byte[] bytes) => Convert.ToHexString(SHA256.HashData(bytes));
    static FiniteIslandSurface Flat() => new(new FiniteIslandLayout(1,1));

    [Test] public void SavedBasisEulerAndScaleMatchGodotAtGimbalAndMirroredCases()
    {
        int[] Bits(Vector3 v) => new[] {v.X,v.Y,v.Z}.Select(BitConverter.SingleToInt32Bits).ToArray();
        var values=new List<object>();
        foreach(float x in new[]{-90f,-89.999f,-20f,0f,38f,89.999f,90f,270f})
        foreach(float y in new[]{0f,23f,180f})
        foreach(float z in new[]{0f,-49f})
        foreach(var scale in new[]{new Vector3(1,1,1),new Vector3(2,.35f,4),new Vector3(-2,3,4)})
        {
            var basis=FiniteIslandObjects.FromEuler(x,y,z)*Basis.FromScale(scale);
            var unit=basis.Orthonormalized();
            values.Add(new {x,y,z,scale,determinant=BitConverter.SingleToInt32Bits(basis.Determinant()),
                axes=new[]{Bits(unit.X),Bits(unit.Y),Bits(unit.Z)},scaleBits=Bits(basis.Scale),euler=Bits(unit.GetEuler())});
        }
        // Independently generated by actual GodotSharp 4.6, not this shim.
        Assert.That(Hash(JsonSerializer.SerializeToUtf8Bytes(values,new JsonSerializerOptions {IncludeFields=true})),
            Is.EqualTo("CB87EBA3308916D1FB4360A91CBFB0C3768C3AF0C92AB5A2E331CFB36AFACA71"));
    }

    [Test] public void SourcePropTextAndReopenedBasesMatchRealGodot()
    {
        string content=Path.Combine(Root(),"game/content");
        var g=FiniteIslandGeneration.Generate(content,temporary,1,1,1234,false);
        Assert.That(g.Objects.SaveProps(At("props.txt")),Is.EqualTo(759));
        Assert.That(Hash(File.ReadAllBytes(At("props.txt"))),Is.EqualTo(
            "7FAB3E054C67997F06B332F6565F0FCA6D412752A0CFC35A5ABAFAEFAB6DA5FB"));
        var loaded=new FiniteIslandObjects(content);
        loaded.LoadProps(At("props.txt"));
        var data=loaded.Placements.Select(o=>new {o.Name,o.Position,o.Material,X=o.Basis.X,Y=o.Basis.Y,Z=o.Basis.Z}).ToArray();
        Assert.That(Hash(JsonSerializer.SerializeToUtf8Bytes(data,new JsonSerializerOptions {IncludeFields=true})),
            Is.EqualTo("8A8647A7DEE8704E6C006D911C8739C1D764F2F0DA4328F9E6AC3AAA0E563E64"));
        Assert.That(g.Roads.SavePaths(At("Paths.dat")),Is.True);
        var roads=new FiniteIslandRoads(Flat(),temporary);
        roads.LoadPaths(At("Paths.dat"));
        roads.SavePaths(At("reopened.dat"));
        Assert.That(File.ReadAllBytes(At("reopened.dat")),Is.EqualTo(File.ReadAllBytes(At("Paths.dat"))));
    }

    [Test] public void PropReaderKeepsFirstAliasMaterialAndSourceZeroScaleFallback()
