    [TestCase(2)] [TestCase(3)] [TestCase(4)] [TestCase(5)] [TestCase(6)]
    public void RoadReaderRoundTripsEverySourceVersionAndRetainsStateOnTruncation(byte version)
    {
        using(var w=new BinaryWriter(File.Create(At("paths.dat"))))
        {
            w.Write(version);w.Write((ushort)2);
            for(int r=0;r<2;r++)
            {
                w.Write((ushort)r);w.Write((byte)5);
                if(version>2)w.Write(true);
                if(version>=6){w.Write((ushort)3);w.Write(new byte[]{12,33,54});}
                if(r==0)continue;
                w.Write(1.25f);w.Write(3.5f);w.Write(9.75f);
                if(version>2){for(int i=0;i<6;i++)w.Write(i*.25f);w.Write((byte)2);}
                if(version>4)w.Write(1.125f);
                if(version>3)w.Write(true);
            }
        }
        var roads=new FiniteIslandRoads(Flat(),temporary);
        roads.LoadPaths(At("paths.dat"));
        Assert.That(roads.RoadCount,Is.EqualTo(2),"degenerate source roads keep their indices");
        Assert.That(roads.JointPos(1,0).Z,Is.EqualTo(-9.75));
        roads.SavePaths(At("output.dat"));
        Assert.That(File.ReadAllBytes(At("output.dat")),Is.EqualTo(File.ReadAllBytes(At("paths.dat"))));
        File.WriteAllBytes(At("truncated.dat"),new byte[]{6,2});
        Assert.Throws<EndOfStreamException>(()=>roads.LoadPaths(At("truncated.dat")));
        roads.SavePaths(At("output.dat"));
        Assert.That(File.ReadAllBytes(At("output.dat")),Is.EqualTo(File.ReadAllBytes(At("paths.dat"))));
    }

