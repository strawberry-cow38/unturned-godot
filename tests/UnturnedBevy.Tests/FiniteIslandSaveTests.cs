    string temporary;
    static string Root()
    {
        for (var d=new DirectoryInfo(TestContext.CurrentContext.TestDirectory);d!=null;d=d.Parent)
            if (Directory.Exists(Path.Combine(d.FullName,"game/content"))) return d.FullName;
