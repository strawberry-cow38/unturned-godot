        sealed partial class Furnisher
        {
            bool HomeHere => _res.Kind is BuildingKind.Residential or BuildingKind.Apartment;
            /// <summary>Is this room a child's -- a bedroom with a single bed or bunks -- or, for any other room, has its home
            /// one furnished yet (a storey's rooms are furnished before the next storey's)?</summary>
            bool KidHere(RoomKind kind) => kind == RoomKind.Bedroom
                ? _mine.Any(m => m.Name is "Bed_1" or "Bed_2")
                : _res.Furniture.Any(m => m.Room != null && m.Room.Kind == RoomKind.Bedroom && m.Room.Unit == _room.Unit && m.Name is "Bed_1" or "Bed_2");

            /// <summary>The kit's rows this room takes, by mount: its kind among the row's room kinds; a home's household set,
            /// a business's work rooms only the WorkDoodads; a toy only in a child's home, never in an office.</summary>
            List<DoodadRow> DoodadRows(DoodadMount mount)
            {
                string kind = _room.Kind.ToString();
                return DoodadKit.Where(r => !r.Outdoor && r.Mount == mount && r.Rooms.Contains(kind)
                                            && (HomeHere || (WorkRooms.Contains(_room.Kind) && WorkDoodads.Contains(r.Name)))
                                            && (!ChildishDoodads.Contains(r.Name) || (HomeHere && _room.Kind != RoomKind.Office && KidHere(_room.Kind)))).ToList();
            }

            void ToldDoodad(FurniturePlan m, DoodadRow row)
            {
                FurnishTrace?.Invoke($"doodad {m}{(m.On != null ? " on " + m.On.Name : "")}");
                DoodadTrace?.Invoke(m, row);
            }

            // ---- the anchors: what a row likes to be near, or keeps away from, as boxes in plan ----

            static readonly Dictionary<string, string[]> AnchorPieces = new()
            {
                ["Fridge"] = new[] { "Fridge" }, ["Stove"] = new[] { "Oven" }, ["Sink"] = new[] { "Counter_1" },
                ["Counter"] = new[] { "Counter_0", "Counter_2", "Corner_Cabinet" }, ["DiningTable"] = new[] { "Table_Wood_0", "Table_Wood_1", "Table_Wood_3" },
                ["Couch"] = new[] { "Couch" }, ["Bed"] = new[] { "Bed" }, ["Workbench"] = new[] { "Table_Metal_0", "Craft_01" },
                ["Tub"] = new[] { "Tub" }, ["TV"] = new[] { "Television" }, ["Wardrobe"] = new[] { "Wardrobe" },
            };

            /// <summary>Where the kit's anchor word stands in this room, as boxes in plan; empty where it has none ("Toilet":
            /// the generator places no toilet).</summary>
            List<(float X0, float Z0, float X1, float Z1)> Anchors(string word)
            {
                var l = new List<(float, float, float, float)>();
                if (AnchorPieces.TryGetValue(word, out var pre))
                    l.AddRange(_mine.Where(m => !m.Ceiling && pre.Any(m.Name.StartsWith)).Select(m => m.Footprint));
                else if (word == "Desk")
                    l.AddRange(_mine.Where(m => m.Name == "Table_Wood_2" && _res.Furniture.Any(t => t.On == m && t.Name == "Computer_3")).Select(m => m.Footprint));
                else if (word == "Window")
                    foreach (var (w, o, side) in Windows().Where(q => q.O.V < 2.5f))
                    {
                        var (dx, dz) = PlanTrig.CosSin(w.Yaw); dz = -dz;
                        float nx = -dz * side, nz = dx * side, t = w.Thickness * 0.5f;
                        float ax = w.X + dx * o.U + nx * t, az = w.Z + dz * o.U + nz * t, bx = w.X + dx * o.U1 + nx * (t + 0.7f), bz = w.Z + dz * o.U1 + nz * (t + 0.7f);
                        l.Add((MathF.Min(ax, bx), MathF.Min(az, bz), MathF.Max(ax, bx), MathF.Max(az, bz)));
                    }
                else if (word == "ExteriorDoor")
                    l.AddRange(DoorsOut(true).Select(p => (p.X - 0.05f, p.Z - 0.05f, p.X + 0.05f, p.Z + 0.05f)));
                else if (word == "Fireplace")
                    l.AddRange(Fires().Where(f => f.Own).Select(f => (f.X0, f.Z0, f.X1, f.Z1)));
                return l;
            }

            /// <summary>The gap between two boxes in plan, 0 where they meet or overlap.</summary>
            static float Gap((float X0, float Z0, float X1, float Z1) a, (float X0, float Z0, float X1, float Z1) b)
            {
                float gx = MathF.Max(0f, MathF.Max(a.X0 - b.X1, b.X0 - a.X1)), gz = MathF.Max(0f, MathF.Max(a.Z0 - b.Z1, b.Z0 - a.Z1));
                return MathF.Sqrt(gx * gx + gz * gz);
            }

            /// <summary>Does a piece at fp come nearer than DoodadAvoidGap to anything its row avoids? (Door and Stairs are the
            /// floor plan's own: Put keeps every piece out of doorways and off the stairs.)</summary>
            bool Avoids(DoodadRow row, (float X0, float Z0, float X1, float Z1) fp)
                => row.Avoid.Where(a => a is not ("Door" or "Stairs")).SelectMany(Anchors).Any(b => Gap(fp, b) < DoodadAvoidGap);

            /// <summary>How near a piece at fp is to what its row likes, best 0: minus the gap to the nearest anchor, and a
            /// corner where the row likes one.</summary>
            double Nearness(DoodadRow row, string name, (float X, float Z, float Yaw) p)
            {
                var fp = FurnitureCatalog.Footprint(name, p.X, p.Z, p.Yaw);
                double best = double.NegativeInfinity;
                foreach (var word in row.Near)
                {
                    if (word == "Corner") { if (Corner(name, p)) best = Math.Max(best, 0); continue; }
                    foreach (var b in Anchors(word)) best = Math.Max(best, -Gap(fp, b));
                }
                return double.IsNegativeInfinity(best) ? -3 : best;
            }

            // ---- floor pieces: with the plants, before the décor, into Furniture ----

            /// <summary>The kit's floor pieces (the umbrella stand, the hamper, the speakers...): in the rooms their rows name,
            /// at their odds, each through Put -- clear floor of the room, out of every doorway, door's and drawer's swing,
            /// stair, flight's end tile and hole, the room still walkable to every door and every piece's front -- its back to
            /// a wall where the row says so; the clear floor its row asks for in front of it (StandClear), Spacing off every
            /// other piece standing (a plant's leaves too), from under anything hung lower than its top, out of the windows'
            /// and the fire's zones when it is taller than a sill, DoodadAvoidGap off what it avoids; nearest what it likes.
            /// After the plants and before the wall décor, which then keeps clear of it as of any piece; the rugs, laid
            /// later, lie round it. Its draws are the room's own (OwnRng), so nothing else in the building moves.</summary>
            public void FloorDoodads()
            {
                var rows = DoodadRows(DoodadMount.Floor);
                if (rows.Count == 0) return;
                var rng = OwnRng(0xD0D1);
                foreach (var row in rows)
                    for (int n = 0; n < row.Max; n++)
                    {
                        if (rng.Int(100) >= DoodadChance(row.Rarity)) break;
                        var m = FloorDoodad(row, rng);
                        if (m == null) break;
                        ToldDoodad(m, row);
                    }
            }

            FurniturePlan FloorDoodad(DoodadRow row, Rng rng)
            {
                string name = row.Name;
                var s = FurnitureCatalog.Sizes[name];
                List<(float X0, float Z0, float X1, float Z1)> need = null; float reach = 0f;
                if (NeedsNear.TryGetValue(name, out var nn) && (nn.Only == null || nn.Only == _room.Kind))
                {
                    need = Anchors(nn.Anchor); reach = nn.Reach;
                    if (need.Count == 0) return null;
                }
                bool back = row.AgainstWall || row.Yaw is DoodadYaw.BackToWall or DoodadYaw.FaceRoom;
                var cands = (back ? Against(name, Side.Back) : Against(name, Side.Back).Concat(Against(name, Side.Left)).Concat(Against(name, Side.Right)))
                    .Where(p =>
                    {
                        var fp = FurnitureCatalog.Footprint(name, p.X, p.Z, p.Yaw);
                        if (need != null && need.Min(b => Gap(fp, b)) > reach) return false;
                        if (s.H > WallOpenings.WindowSill && BlocksWindow(fp)) return false;
                        if (UnderHung(fp, s.H)) return false;
                        var me = new FurniturePlan { Name = name, X = p.X, Z = p.Z, Yaw = p.Yaw };
                        if (_mine.Any(o => o.On == null && !o.Mounted && !o.Ceiling && FurnitureCatalog.Intersects(me, o, -row.Spacing))) return false;
                        if (row.ClearFront > 0f && !StandClear(name, p.X, p.Z, p.Yaw, row.ClearFront)) return false;
                        return !Avoids(row, fp);
                    }).ToList();
                if (cands.Count == 0) return null;
                return Put(name, cands, (x, z, yaw) => Nearness(row, name, (x, z, yaw)), 0f, rng);
            }

            // ---- tops: once the whole building is furnished, into Doodads ----

            /// <summary>A surface a doodad can stand on, in a frame of its own: origin (X, Z), turned Yaw (its Front and Right as
            /// a piece's), the surface at Y; the usable rectangle across (A) and front-to-back (B) in that frame, with holes in
            /// it (a basin) and, for a round table, its disc (R > 0), for a corner cabinet its diagonal (Cut: A + B at most);
            /// how much headroom it has (a shelf's tier: to the board over it); which quarter turn faces whoever uses it
            /// (Face: 0 the frame's front, 2 its back -- a desk's chair); its back to a wall (Backed) -- things go to the back;
            /// and the kit's host words it serves as.</summary>
            sealed class Top
            {
                public FurniturePlan Host; public string[] Serves;
                public float X, Z, Yaw, Y, A0, A1, B0, B1, R, Cut = float.NaN, Room = float.PositiveInfinity;
                public int Face; public bool Backed;
                public List<(float A0, float A1, float B0, float B1)> Holes = new();
                public (float X, float Z) At(float a, float b)
                {
                    var (c, sn) = PlanTrig.CosSin(Yaw);
                    // right (c, -sn) and front (-sn, -c), as FurniturePlan's
                    return (X + c * a - sn * b, Z - sn * a - c * b);
                }
            }

            /// <summary>A shelf's tiers: each board's top over the shelf's origin, the headroom to the board over it, and the
            /// stretch of it inside the uprights and the back -- read off the OBJs (their horizontal faces).</summary>
            static readonly Dictionary<string, (float Top, float Room, float A0, float A1, float B0, float B1)[]> Tiers = new()
            {
                ["Shelf_2"] = new[] { (0.95f, 0.70f, -1.25f, 1.25f, -0.25f, 0.50f), (1.775f, 0.70f, -1.25f, 1.25f, -0.25f, 0.50f), (2.60f, float.PositiveInfinity, -1.375f, 1.38f, -0.375f, 0.50f) },
                ["Shelf_3"] = new[] { (0.325f, 0.60f, -0.75f, 0.75f, -1.0f, 1.0f), (1.05f, 0.60f, -0.75f, 0.75f, -1.0f, 1.0f), (1.775f, float.PositiveInfinity, -0.75f, 0.75f, -1.0f, 1.0f) },
                ["Shelf_0"] = new[] { (0.375f, 0.625f, -0.88f, 0.88f, -1.178f, 1.178f), (1.125f, 0.625f, -0.88f, 0.88f, -1.178f, 1.178f), (1.875f, float.PositiveInfinity, -0.88f, 0.88f, -1.178f, 1.178f) },
            };

            /// <summary>The tops of this room (see DoodadHostMap): its pieces' and its windows' sills.</summary>
            List<Top> Tops()
            {
                var l = new List<Top>();
                bool desk = _mine.Any(m => m.Name == "Table_Wood_2" && _room.Kind == RoomKind.Office);
                Top Of(FurniturePlan h, float y, float a0, float a1, float b0, float b1, params string[] serves)
                    => new Top { Host = h, X = h.X, Z = h.Z, Yaw = h.Yaw, Y = y, A0 = a0, A1 = a1, B0 = b0, B1 = b1, Serves = serves, Backed = h.Mounted || Backed(h.Name, h.X, h.Z, h.Yaw) };
                foreach (var h in _mine.Where(m => m.On == null && !m.Ceiling))
                {
                    var s = FurnitureCatalog.Sizes[h.Name];
                    switch (h.Name)
                    {
                        case "Counter_0" or "Counter_2" when !h.Mounted:
                        {
                            var t = Of(h, h.Y + s.H, s.X0, s.X1, s.Y0, s.Y1);
                            t.Serves = t.Backed ? new[] { "Counter" } : new[] { "KitchenIsland" };
                            l.Add(t); break;
                        }
                        case "Corner_Cabinet_0_Solid" or "Corner_Cabinet_1_Solid":
                        {
                            // its diagonal front cuts the +X/+Y corner off the square, 0.625 m along each side (its top's area)
                            var t = Of(h, h.Y + s.H, s.X0, s.X1, s.Y0, s.Y1, "Counter");
                            t.Cut = s.X1 + s.Y1 - 0.625f; l.Add(t); break;
                        }
                        case "Counter_1" when _room.Kind == RoomKind.Bathroom:
                        {
                            // the basin's top is 1.35 m (its tap stands to Sizes' 1.83): the basin and the tap's foot are holes
                            var t = Of(h, h.Y + 1.35f, s.X0, s.X1, s.Y0, s.Y1, "BathroomCounter");
                            t.Holes.Add((-0.55f, 0.55f, -0.30f, 0.30f)); t.Holes.Add((-0.27f, 0.27f, s.Y0, -0.13f));
                            l.Add(t); break;
                        }
                        case "Washer_0" when _room.Kind == RoomKind.Bathroom:
                            l.Add(Of(h, h.Y + s.H, s.X0, s.X1, s.Y0, s.Y1, "BathroomCounter")); break;
                        case "Table_Wood_0" or "Table_Wood_1" or "Table_Wood_3" when _room.Kind is RoomKind.Kitchen or RoomKind.DiningRoom or RoomKind.BreakRoom:
                        {
                            var t = Of(h, h.Y + s.H, s.X0, s.X1, s.Y0, s.Y1, "DiningTable");
                            if (FurnitureCatalog.Round.TryGetValue(h.Name, out var r)) t.R = r;
                            l.Add(t); break;
                        }
                        case "Table_Wood_2" when _room.Kind == RoomKind.LivingRoom:
                            l.Add(Of(h, h.Y + s.H, s.X0, s.X1, s.Y0, s.Y1, "CoffeeTable", "SideTable")); break;
                        case "Table_Wood_2" when _room.Kind == RoomKind.Office:
                        {
                            // the user sits at its back, facing the monitor (Office: the desk turned as its chair)
                            var t = Of(h, h.Y + s.H, s.X0, s.X1, s.Y0, s.Y1, "Desk"); t.Face = 2; l.Add(t); break;
                        }
                        case "Table_Metal_0":
                            l.Add(Of(h, h.Y + s.H, s.X0, s.X1, s.Y0, s.Y1, "Workbench")); break;
                        case "Wall_Shelf_0" or "Wall_Shelf_2" when h.Mounted:
                            l.Add(Of(h, h.Y + s.H, s.X0, s.X1, s.Y0, s.Y1, desk ? new[] { "WallShelf", "Shelf" } : new[] { "WallShelf", "Shelf", "Desk" })); break;
                    }
                    if (!h.Mounted && Tiers.TryGetValue(h.Name, out var tiers))
                        foreach (var (top, room, a0, a1, b0, b1) in tiers)
                        {
                            var t = Of(h, h.Y + top, a0, a1, b0, b1, desk ? new[] { "Shelf" } : new[] { "Shelf", "Desk" });
                            t.Room = room; l.Add(t);
                        }
                }
                // the sills: a glazed window's reveal on this room's side, from SillPaneClear off the glass to the wall's face
                foreach (var (w, o, side) in Windows())
                {
                    if (!o.Glazed || o.Archetype is not (ArchWindow or ArchTallWindow) || o.V < 0.5f || o.V > 1.6f) continue;
                    var (dx, dz) = PlanTrig.CosSin(w.Yaw); dz = -dz;
                    float nx = -dz * side, nz = dx * side, t = w.Thickness * 0.5f, u = (o.U + o.U1) * 0.5f;
                    l.Add(new Top
                    {
                        X = w.X + dx * u + nx * t, Z = w.Z + dz * u + nz * t, Yaw = YawFacing(nx, nz), Y = w.Y + o.V,
                        A0 = -o.Width * 0.5f, A1 = o.Width * 0.5f, B0 = -(t - SillPaneClear), B1 = 0f, Room = o.Height,
                        Serves = new[] { "Windowsill" }, Backed = true,
                    });
                }
                return l;
            }

            /// <summary>What already stands on a top: the furniture's (an appliance, a plant, the monitor) and the kit's, on that
            /// host at that height -- or, on a sill, on the same window.</summary>
            IEnumerable<FurniturePlan> OnTop(Top t)
                => t.Host != null
                    ? _res.Furniture.Where(m => m.On == t.Host && MathF.Abs(m.Y - t.Y) < 0.02f).Concat(_res.Doodads.Where(m => m.On == t.Host && MathF.Abs(m.Y - t.Y) < 0.02f))
                    : _res.Doodads.Where(m => m.On == null && m.Room == _room && MathF.Abs(m.Y - t.Y) < 0.02f && MathF.Abs(m.X - t.X) + MathF.Abs(m.Z - t.Z) < 3f);

            /// <summary>The kit's tops: each surface piece its rows' odds put in the room, on a top that serves as one of its
            /// row's hosts (DoodadHostMap) -- the whole of it on the top, EdgeMargin in from its edges and its holes, under
            /// the top's headroom; Spacing off whatever else stands on it, DoodadsPerHost and ItemsPerHost a top at most; from
            /// under anything hung lower than its top; not taller than a sill's height plus 0.5 m in front of a window;
            /// DoodadAvoidGap off what it avoids; turned as its row says. Best: nearest what it likes, at the back of a top
            /// against a wall, a tier at about eye height. Once every storey is furnished (a child's room upstairs is known
            /// downstairs), on the room's own draws, into BuildingGenResult.Doodads -- kept out of Furniture, which every
            /// placement rule reads as solid pieces standing on a catalog top (a basin's counter, a sill, a shelf's middle
            /// tier are not where the catalog's sizes put a top).</summary>
            public void TopDoodads()
            {
                var rows = DoodadRows(DoodadMount.Surface);
                if (rows.Count == 0) return;
                var tops = Tops();
                if (tops.Count == 0) return;
                var rng = OwnRng(0x70D5);
                foreach (var row in rows)
                    for (int n = 0; n < row.Max; n++)
                    {
                        if (rng.Int(100) >= DoodadChance(row.Rarity)) break;
                        var m = TopDoodad(row, tops, rng);
                        if (m == null) break;
                        _res.Doodads.Add(m);
                        ToldDoodad(m, row);
                    }
            }

            /// <summary>An item's extents in a frame when turned k quarters from it (FurnitureCatalog's conventions: its X along
            /// the frame's right, its Y along the frame's front, at k = 0).</summary>
            static (float A0, float A1, float B0, float B1) Turned(FurnitureCatalog.Size s, int k) => (k % 4) switch
            {
                0 => (s.X0, s.X1, s.Y0, s.Y1),
                1 => (-s.Y1, -s.Y0, s.X0, s.X1),
                2 => (-s.X1, -s.X0, -s.Y1, -s.Y0),
                _ => (s.Y0, s.Y1, -s.X1, -s.X0),
            };

            /// <summary>The quarter turns a row tries on a top, best first.</summary>
            static List<int> Turns(DoodadRow row, Top t, Rng rng)
            {
                int f = t.Face;
                switch (row.Yaw)
                {
                    case DoodadYaw.FaceRoom or DoodadYaw.BackToWall:
                        return t.Backed || t.Host == null ? new List<int> { f } : new List<int> { f, (f + 1) % 4, (f + 3) % 4, (f + 2) % 4 };
                    case DoodadYaw.AlignToHostEdge:
                        // its long side (X) along the top's long side, its front to whoever uses it where it can
                        return t.A1 - t.A0 >= t.B1 - t.B0 ? new List<int> { f, (f + 2) % 4 } : new List<int> { (f + 1) % 4, (f + 3) % 4 };
                    default:
                    {
                        var l = new List<int> { 0, 1, 2, 3 };
                        rng.Shuffle(l);
                        return l;
                    }
                }
            }

            FurniturePlan TopDoodad(DoodadRow row, List<Top> tops, Rng rng)
            {
                string name = row.Name;
                var s = FurnitureCatalog.Sizes[name];
                float floorY = _room.Floor * Storey, m = MathF.Max(row.EdgeMargin, 0.02f);
                var avoid = row.Avoid.Where(a => a is not ("Door" or "Stairs")).SelectMany(Anchors).ToList();
                var cands = new List<(Top T, float A, float B, int K, double Score)>();
                foreach (var t in tops)
                {
                    if (!row.Hosts.Any(h => t.Serves.Contains(h)) || t.Room < s.H + 0.03f) continue;
                    if (MathF.Max(t.A1 - t.A0, t.B1 - t.B0) < row.MinLongTop) continue;
                    if (t.Host != null)
                    {
                        var on = OnTop(t).ToList();
                        if (on.Count >= ItemsPerHost || on.Count(o => DoodadKit.Any(r => r.Name == o.Name)) >= DoodadsPerHost) continue;
                    }
                    double tier = t.Host != null && Tiers.ContainsKey(t.Host.Name) ? -0.3 * MathF.Abs(t.Y - floorY - 1.4f) : 0;
                    foreach (int k in Turns(row, t, rng))
                    {
                        var (e0, e1, f0, f1) = Turned(s, k);
                        float aLo = t.A0 + m - e0, aHi = t.A1 - m - e1, bLo = t.B0 + m - f0, bHi = t.B1 - m - f1;
                        if (aHi < aLo - 1e-4f || bHi < bLo - 1e-4f) continue;
                        var bs = new List<float> { bLo };
                        for (float b = bLo + 0.1f; b < bHi; b += 0.1f) bs.Add(b);
                        if (bHi > bLo + 1e-3f) bs.Add(bHi);
                        for (float a = aLo; a <= aHi + 1e-4f; a += 0.05f)
                            foreach (float b in bs)
                            {
                                // to the back of a top against a wall; on a free one, anywhere
                                double score = (t.Backed ? -0.6 * (b - bLo) : 0) + tier + rng.Int(1000) * 1e-4;
                                cands.Add((t, a, b, k, score));
                            }
                    }
                }
                // what it likes, nearest first: measured once per candidate, after the draws above are all taken
                var near = row.Near.SelectMany(Anchors).ToList();
                var ranked = cands.Select(c =>
                {
                    var (e0, e1, f0, f1) = Turned(s, c.K);
                    var p0 = c.T.At(c.A + e0, c.B + f0); var p1 = c.T.At(c.A + e1, c.B + f1);
                    var fp = (MathF.Min(p0.X, p1.X), MathF.Min(p0.Z, p1.Z), MathF.Max(p0.X, p1.X), MathF.Max(p0.Z, p1.Z));
                    return (c.T, c.A, c.B, c.K, Fp: fp, Score: c.Score - (near.Count > 0 ? 0.5 * near.Min(b => Gap(fp, b)) : 0));
                }).OrderByDescending(c => c.Score).ToList();
                foreach (var (t, a, b, k, fp, _) in ranked)
                {
                    var (e0, e1, f0, f1) = Turned(s, k);
                    float x0 = a + e0, x1 = a + e1, y0 = b + f0, y1 = b + f1;
                    if (t.Holes.Any(h => x0 < h.A1 + m && x1 > h.A0 - m && y0 < h.B1 + m && y1 > h.B0 - m)) continue;
                    if (t.R > 0f && new[] { (x0, y0), (x1, y0), (x0, y1), (x1, y1) }.Any(q => MathF.Sqrt(q.Item1 * q.Item1 + q.Item2 * q.Item2) > t.R - m)) continue;
                    if (!float.IsNaN(t.Cut) && x1 + y1 > t.Cut - m) continue;
                    if (OnTop(t).Any(o => Overlaps(Grow(fp, row.Spacing), o.Footprint))) continue;
                    float top = t.Y - floorY + s.H;
                    if (HungOver(fp, top, t.Host)) continue;
                    if (t.Host != null && SillBehind(fp) is float sill && top > sill + 0.5f) continue;
                    if (avoid.Any(q => Gap(fp, q) < DoodadAvoidGap)) continue;
                    var (cx, cz) = t.At(a, b);
                    return new FurniturePlan { Name = name, X = cx, Y = t.Y, Z = cz, Yaw = ((t.Yaw + 90f * k) % 360f + 360f) % 360f, Floor = _room.Floor, Room = _room, On = t.Host };
                }
                return null;
            }

            /// <summary>Is anything hung on this floor (but `except`, the shelf a piece stands on) or hanging from the ceiling
            /// within PlantClear of fp, its bottom lower than `top` (over the floor) and PlantClear?</summary>
            bool HungOver((float X0, float Z0, float X1, float Z1) fp, float top, FurniturePlan except)
                => _res.Furniture.Any(o => o != except && o.Floor == _room.Floor && Overlaps(Grow(fp, PlantClear), o.Footprint)
                                           && (o.Mounted ? o.Y - FurnitureCatalog.Sizes[o.Name].H : o.Ceiling ? o.Y - (o.Name.Contains("Pendant") ? PendantDrop : 0.28f) : float.MaxValue)
                                              < _room.Floor * Storey + top + PlantClear);

            /// <summary>The lowest sill (over the floor) of a window whose zone a box stands in -- across the opening and
            /// PlantWindowGap either side, 0.7 m into the room -- or null.</summary>
            float? SillBehind((float X0, float Z0, float X1, float Z1) fp)
            {
                float? low = null;
                foreach (var (w, o, side) in Windows())
                {
                    if (o.V >= 2.5f) continue;
                    var (dx, dz) = PlanTrig.CosSin(w.Yaw); dz = -dz;
                    float nx = -dz * side, nz = dx * side, t = w.Thickness * 0.5f + 0.7f;
                    float ax = w.X + dx * (o.U - PlantWindowGap), az = w.Z + dz * (o.U - PlantWindowGap), bx = w.X + dx * (o.U1 + PlantWindowGap), bz = w.Z + dz * (o.U1 + PlantWindowGap);
                    var zone = (MathF.Min(MathF.Min(ax, bx), MathF.Min(ax, bx) + nx * t), MathF.Min(MathF.Min(az, bz), MathF.Min(az, bz) + nz * t),
                                MathF.Max(MathF.Max(ax, bx), MathF.Max(ax, bx) + nx * t), MathF.Max(MathF.Max(az, bz), MathF.Max(az, bz) + nz * t));
                    if (!Overlaps(fp, zone)) continue;
                    float sill = w.Y + o.V - _room.Floor * Storey;
                    low = low == null ? sill : MathF.Min(low.Value, sill);
                }
                return low;
            }
        }

        // ---- outside: the yard, the porch, the house's outside walls, into Doodads ----

        /// <summary>The kit's outdoor pieces (the lead: "flamingos, birdbath, kennel, compost, sandbox, stepping stones,
        /// tricycle, garden tools, bird feeder, wind chime"), once every storey is furnished: a house's yard, porch and outside
        /// walls take its household set; a business's back and side walls a cardboard stack or two (its row's kerb and alley),
        /// a house's only by its garage. A block of flats has no yard of its own. On the building's own draws (seed), into
        /// BuildingGenResult.Doodads -- with no room (Room null), as outside is none.</summary>
        static void Outdoors(BuildingGenResult res, int seed)
        {
            bool house = res.Kind == BuildingKind.Residential, business = res.Kind is BuildingKind.Commercial or BuildingKind.Industrial;
            if (!house && !business) return;
            var yard = new Yard(res);
            if (yard.Faces.Count == 0) return;
            var rng = new Rng(unchecked(seed * 486187739 ^ 0x7A4D));
            bool kids = res.Furniture.Any(m => m.Room != null && m.Room.Kind == Bedroom && m.Name is "Bed_1" or "Bed_2");
            foreach (var row in DoodadKit.Where(r => r.Outdoor))
            {
                bool cardboard = row.Name == "Bound_Cardboard_Stack_0";
                if (house ? cardboard && !yard.Garage : !cardboard) continue;
                if (ChildishDoodads.Contains(row.Name) && !kids) continue;
                for (int n = 0; n < row.Max;)
                {
                    if (rng.Int(100) >= DoodadChance(row.Rarity)) break;
                    int size = Math.Min(row.Max - n, row.ClusterMin + (row.ClusterMax > row.ClusterMin ? rng.Int(row.ClusterMax - row.ClusterMin + 1) : 0));
                    var got = yard.Place(row, rng, size);
                    if (got.Count == 0) break;
                    foreach (var m in got) { res.Doodads.Add(m); FurnishTrace?.Invoke($"doodad {m.Name} at ({m.X:0.00},{m.Y:0.00},{m.Z:0.00}) yaw {m.Yaw:0} outside"); DoodadTrace?.Invoke(m, row); }
                    n += got.Count;
                }
            }
        }

        /// <summary>A building's outside, for the yard pieces: the outside faces of its ground storey's outside walls, what
        /// nothing outside may stand in (its walls, the porch posts, the chimney), the walks kept clear from its doors out
        /// (a vehicle door's lane) and off its porches, its porch decks and the underside of their roofs, and what the yard
        /// already holds.</summary>
        sealed class Yard
        {
            public sealed class Face
            {
                public WallPlan W; public float Dx, Dz, Nx, Nz, T, Len; public bool Front; public GenRoom Inside;
                /// <summary>u along the wall, s out from its outside face.</summary>
                public (float X, float Z) At(float u, float s) => (W.X + Dx * u + Nx * (T + s), W.Z + Dz * u + Nz * (T + s));
                public float Yaw => YardYaw(Nx, Nz);
            }
            sealed class Deck
            {
                public (float X0, float Z0, float X1, float Z1) Box; public Face Face; public float Depth, PostH = float.NaN, Tan;
                public List<(float X0, float Z0, float X1, float Z1)> Walks = new();
                /// <summary>The porch roof's underside over a point s out from the house's face.</summary>
                public float Underside(float s) => PostH + ((Depth - PorchPost) - s) * Tan;
            }
            readonly BuildingGenResult _res;
            public readonly List<Face> Faces = new();
            readonly List<Deck> _decks = new();
            readonly List<(float X0, float Z0, float X1, float Z1)> _solid = new(), _walks = new();
            readonly List<(float X, float Z, float Sill, float U0, float U1, Face F)> _windows = new();
            readonly List<(float X, float Z, int Role)> _doors = new();   // Role: 2 back, 1 front, 0 another
            readonly List<(FurniturePlan M, DoodadRow Row)> _placed = new();
            readonly (float X0, float Z0, float X1, float Z1) _box;
            public bool Garage;

            public Yard(BuildingGenResult res)
            {
                _res = res;
                bool Ground(WallPlan w) => (int)MathF.Round(w.Y / Storey) == 0;
                foreach (var w in res.Walls.Where(w => (w.Kind == SurfaceKind.Wall || w.Kind == SurfaceKind.Foundation) && Ground(w)))
                    if (w.Kind == SurfaceKind.Wall) _solid.Add(Box(w));
                var c = res.Chimney;
                if (c.X1 > c.X0) _solid.Add(Grow(c, 0.2f));
                // a basement's hatch -- its well, and the cellar door thrown open beside it -- and the way onto its stairs
                if (res.HatchWell.X1 > res.HatchWell.X0) { _solid.Add(Grow(res.HatchWell, 1.0f)); _solid.Add(Grow(res.HatchLeafRect, 0.5f)); }
                if (_solid.Count == 0) return;
                _box = (_solid.Min(b => b.X0), _solid.Min(b => b.Z0), _solid.Max(b => b.X1), _solid.Max(b => b.Z1));
                // the outside faces: a full-storey outside wall of the ground storey, the side of it with no room
                foreach (var w in res.Walls.Where(w => w.Kind == SurfaceKind.Wall && Ground(w) && w.Thickness >= Ext - 0.01f && w.Height >= Storey - 0.01f))
                {
                    var (dx, dz) = PlanTrig.CosSin(w.Yaw); dz = -dz;
                    float t = w.Thickness * 0.5f, mu = w.Length * 0.5f;
                    foreach (int sg in new[] { 1, -1 })
                    {
                        float nx = -dz * sg, nz = dx * sg;
                        float ox = w.X + dx * mu + nx * (t + 0.6f), oz = w.Z + dz * mu + nz * (t + 0.6f);
                        float ix = w.X + dx * mu - nx * (t + 0.6f), iz = w.Z + dz * mu - nz * (t + 0.6f);
                        if (res.Layout.Any(g => g.Floor == 0 && g.Holds(ox, oz))) continue;
                        var inside = res.Layout.FirstOrDefault(g => g.Floor == 0 && g.Holds(ix, iz));
                        if (inside == null) continue;
                        var f = new Face { W = w, Dx = dx, Dz = dz, Nx = nx, Nz = nz, T = t, Len = w.Length, Inside = inside };
                        if (res.Front != null)
                        {
                            var (px, pz) = res.Front.Middle;
                            float along = (px - w.X) * dx + (pz - w.Z) * dz, across = MathF.Abs((px - w.X) * nx + (pz - w.Z) * nz);
                            f.Front = along > -0.1f && along < w.Length + 0.1f && across < t + 0.1f;
                        }
                        if (inside.Kind == RoomKind.Garage) Garage = true;
                        Faces.Add(f);
                        // its openings: the walk out of a door (a vehicle door's lane), the glass of a window
                        foreach (var o in w.Openings)
                        {
                            if (o.V < 0.05f)
                            {
                                float reach = o.Archetype == ArchGarage ? YardLaneWalk : YardDoorWalk;
                                var a = f.At(o.U - YardDoorSide, 0f); var b = f.At(o.U1 + YardDoorSide, reach);
                                _walks.Add((MathF.Min(a.X, b.X), MathF.Min(a.Z, b.Z), MathF.Max(a.X, b.X), MathF.Max(a.Z, b.Z)));
                                if (o.Archetype != ArchGarage)
                                {
                                    var mid = f.At((o.U + o.U1) * 0.5f, 0f);
                                    bool front = res.Front != null && MathF.Abs(res.Front.Middle.X - mid.X) + MathF.Abs(res.Front.Middle.Z - mid.Z) < 1.5f;
                                    bool back = res.Back != null && MathF.Abs(res.Back.Middle.X - mid.X) + MathF.Abs(res.Back.Middle.Z - mid.Z) < 1.5f;
                                    _doors.Add((mid.X, mid.Z, back ? 2 : front ? 1 : 0));
                                }
                            }
                            else if (o.Glazed || o.Archetype is ArchWindow or ArchTallWindow or ArchSlit)
                            {
                                var mid = f.At((o.U + o.U1) * 0.5f, 0f);
                                _windows.Add((mid.X, mid.Z, w.Y + o.V, o.U, o.U1, f));
                            }
                        }
                    }
                }
                // the porches: each deck, the face it stands against, its posts' height, its walk (across it from the door to
                // its open edge, and on out)
                foreach (var d in res.Porches)
                {
                    // (its edge against the house is the face's line: AddPorches lays it from the wall's outside face out)
                    var f = Faces.FirstOrDefault(q =>
                    {
                        var (x, z) = q.At(0f, 0f);
                        bool acrossX = MathF.Abs(q.Nx) > 0.5f;
                        float edge = acrossX ? (q.Nx > 0 ? d.X0 : d.X1) : (q.Nz > 0 ? d.Z0 : d.Z1);
                        return MathF.Abs((acrossX ? x : z) - edge) < 0.1f && Overlap1(q, d);
                    });
                    var deck = new Deck { Box = d, Face = f, Depth = f == null ? 0f : MathF.Abs(f.Nx) > 0.5f ? d.X1 - d.X0 : d.Z1 - d.Z0 };
                    var posts = res.Walls.Where(w => w.Kind == SurfaceKind.Wall && MathF.Abs(w.Thickness - PorchPost) < 0.01f && MathF.Abs(w.Length - PorchPost) < 0.01f
                                                     && Overlaps(Box(w), Grow(d, 0.05f))).ToList();
                    if (posts.Count > 0) { deck.PostH = posts.Min(w => w.Height); deck.Tan = res.Roof == RoofKind.Flat ? 0f : MathF.Tan(PorchPitch * MathF.PI / 180f); }
                    foreach (var p in posts) _solid.Add(Box(p));
                    if (f != null)
                        foreach (var (x, z, _) in _doors)
                        {
                            float along = (x - f.W.X) * f.Dx + (z - f.W.Z) * f.Dz;
                            if (MathF.Abs((x - f.W.X) * f.Nx + (z - f.W.Z) * f.Nz - f.T) > 0.1f || !Inside(d, x + f.Nx * 0.5f, z + f.Nz * 0.5f)) continue;
                            var a = f.At(along - ArchSizes[ArchDoor].W * 0.5f - YardDoorSide, 0f); var b = f.At(along + ArchSizes[ArchDoor].W * 0.5f + YardDoorSide, deck.Depth + YardDoorWalk);
                            var walk = (MathF.Min(a.X, b.X), MathF.Min(a.Z, b.Z), MathF.Max(a.X, b.X), MathF.Max(a.Z, b.Z));
                            deck.Walks.Add(walk); _walks.Add(walk);
                        }
                    _decks.Add(deck);
                }
            }

            static bool Overlap1(Face q, (float X0, float Z0, float X1, float Z1) d)
            {
                var a = q.At(0f, 0f); var b = q.At(q.Len, 0f);
                return MathF.Abs(q.Nx) > 0.5f ? MathF.Min(a.Z, b.Z) < d.Z1 - 0.1f && MathF.Max(a.Z, b.Z) > d.Z0 + 0.1f
                                              : MathF.Min(a.X, b.X) < d.X1 - 0.1f && MathF.Max(a.X, b.X) > d.X0 + 0.1f;
            }
            static bool Inside((float X0, float Z0, float X1, float Z1) b, float x, float z) => x > b.X0 && x < b.X1 && z > b.Z0 && z < b.Z1;
            static (float X0, float Z0, float X1, float Z1) Box(WallPlan w)
            {
                var (wc, ws) = PlanTrig.CosSin(w.Yaw);
                float dx = wc, dz = -ws, t = w.Thickness * 0.5f, ex = w.X + dx * w.Length, ez = w.Z + dz * w.Length;
                float tx = MathF.Abs(dz) * t, tz = MathF.Abs(dx) * t;
                return (MathF.Min(w.X, ex) - tx, MathF.Min(w.Z, ez) - tz, MathF.Max(w.X, ex) + tx, MathF.Max(w.Z, ez) + tz);
            }
            static (float X0, float Z0, float X1, float Z1) Grow((float X0, float Z0, float X1, float Z1) a, float m) => (a.X0 - m, a.Z0 - m, a.X1 + m, a.Z1 + m);
            static bool Overlaps((float X0, float Z0, float X1, float Z1) a, (float X0, float Z0, float X1, float Z1) b)
                => a.X0 < b.X1 - 0.005f && a.X1 > b.X0 + 0.005f && a.Z0 < b.Z1 - 0.005f && a.Z1 > b.Z0 + 0.005f;
            static float Gap((float X0, float Z0, float X1, float Z1) a, (float X0, float Z0, float X1, float Z1) b)
            {
                float gx = MathF.Max(0f, MathF.Max(a.X0 - b.X1, b.X0 - a.X1)), gz = MathF.Max(0f, MathF.Max(a.Z0 - b.Z1, b.Z0 - a.Z1));
                return MathF.Sqrt(gx * gx + gz * gz);
            }
            static bool Within((float X0, float Z0, float X1, float Z1) a, (float X0, float Z0, float X1, float Z1) b, float m)
                => a.X0 >= b.X0 + m && a.X1 <= b.X1 - m && a.Z0 >= b.Z0 + m && a.Z1 <= b.Z1 - m;

            /// <summary>Where a row's pieces go, `size` of them together (a cluster, its row's spacing apart), best first;
            /// none when the first will not go anywhere.</summary>
            public List<FurniturePlan> Place(DoodadRow row, Rng rng, int size)
            {
                var got = new List<FurniturePlan>();
                var first = One(row, rng, null);
                if (first == null) return got;
                got.Add(first); _placed.Add((first, row));
                for (int k = 1; k < size; k++)
                {
                    var m = One(row, rng, got[^1]);
                    if (m == null) break;
                    got.Add(m); _placed.Add((m, row));
                }
                return got;
            }

            FurniturePlan One(DoodadRow row, Rng rng, FurniturePlan beside)
            {
                string name = row.Name;
                var s = FurnitureCatalog.Sizes[name];
                bool porch = row.Rooms.Contains("Porch"), wall = row.Rooms.Contains("ExteriorWall") || row.Mount is DoodadMount.Wall or DoodadMount.Lean;
                var cands = new List<(FurniturePlan M, double Score)>();
                void Add(float x, float y, float z, float yaw, bool mounted, bool ceiling, double score)
                    => cands.Add((new FurniturePlan { Name = name, X = x, Y = y, Z = z, Yaw = yaw, Floor = 0, Mounted = mounted, Ceiling = ceiling }, score + rng.Int(1000) * 1e-3));
                double Near((float X0, float Z0, float X1, float Z1) fp, Face f, float u)
                {
                    double best = -4;
                    float cx = (fp.X0 + fp.X1) * 0.5f, cz = (fp.Z0 + fp.Z1) * 0.5f;
                    foreach (var word in row.Near)
                    {
                        double d = word switch
                        {
                            "Window" => _windows.Count == 0 ? 99 : _windows.Min(q => MathF.Sqrt((q.X - cx) * (q.X - cx) + (q.Z - cz) * (q.Z - cz))),
                            "ExteriorDoor" => _doors.Count == 0 ? 99 : _doors.Min(q => MathF.Sqrt((q.X - cx) * (q.X - cx) + (q.Z - cz) * (q.Z - cz))),
                            "Corner" => f == null ? 99 : MathF.Min(u, f.Len - u),
                            "ExteriorWall" or "Kerb" or "Dumpster" => _solid.Min(b => Gap(fp, b)),
                            _ => 99,
                        };
                        best = Math.Max(best, -0.5 * d);
                    }
                    return best;
                }
                // the face's side: the back yard's pieces behind the house, the lawn's flamingos before it
                double Side(Face f) => f == null ? 0 : name switch
                {
                    "Lawn_Flamingo_Pair_0" => f.Front ? 2 : 0,
                    "Slatted_Compost_Bin_0" or "Garden_Dog_Kennel_0" or "Garden_Sandbox_Frame_0" or "Bound_Cardboard_Stack_0" or "Leaning_Garden_Tools_0" => f.Front ? -4 : 0,
                    _ => 0,
                };
                if (beside != null)
                {
                    // the next of a cluster: along the same wall, ClusterSpacing past the last
                    var f = Faces.Where(q => (beside.X - q.W.X) * q.Dx + (beside.Z - q.W.Z) * q.Dz is var u && u > -1f && u < q.Len + 1f)
                                 .OrderBy(q => MathF.Abs((beside.X - q.W.X) * q.Nx + (beside.Z - q.W.Z) * q.Nz - q.T)).FirstOrDefault();
                    if (f != null)
                    {
                        var bf = beside.Footprint;
                        float step = (MathF.Abs(f.Dx) > 0.5f ? bf.X1 - bf.X0 : bf.Z1 - bf.Z0) + row.ClusterSpacing;
                        foreach (float sg in new[] { 1f, -1f })
                            Add(beside.X + f.Dx * step * sg, beside.Y, beside.Z + f.Dz * step * sg, beside.Yaw, false, false, 0);
                    }
                }
                else if (row.Mount == DoodadMount.Ceiling)
                {
                    // under a porch's roof, its bottom HeadRoom over the deck, off the walk and the posts
                    foreach (var d in _decks.Where(d => d.Face != null && !float.IsNaN(d.PostH)))
                    {
                        var f = d.Face;
                        float u0 = (MathF.Abs(f.Nx) > 0.5f ? d.Box.Z0 : d.Box.X0), u1 = (MathF.Abs(f.Nx) > 0.5f ? d.Box.Z1 : d.Box.X1);
                        for (float sOut = 0.6f; sOut <= d.Depth - 0.6f + 1e-3f; sOut += 0.3f)
                            for (float g = u0 + 0.6f; g <= u1 - 0.6f + 1e-3f; g += 0.5f)
                            {
                                float under = d.Underside(sOut);
                                if (under - row.Drop < HeadRoom) continue;
                                var (x, z) = MathF.Abs(f.Nx) > 0.5f ? (f.At(0f, sOut).X, g) : (g, f.At(0f, sOut).Z);
                                float u = (x - f.W.X) * f.Dx + (z - f.W.Z) * f.Dz;
                                Add(x, under, z, f.Yaw, false, true, Near(FurnitureCatalog.Footprint(name, x, z, f.Yaw), f, u));
                            }
                    }
                }
                else if (row.Mount == DoodadMount.Wall)
                {
                    // on an outside face, its back DecorWallGap off it, at its row's height over the floor
                    foreach (var f in Faces)
                        for (float u = 0.3f - s.X0; u <= f.Len - 0.3f - s.X1 + 1e-3f; u += 0.25f)
                        {
                            var (x, z) = f.At(u, DecorWallGap - s.Y0);
                            bool onDeck = _decks.Any(d => Inside(d.Box, x + f.Nx * 0.5f, z + f.Nz * 0.5f));
                            if (onDeck && !porch || !onDeck && !row.Rooms.Contains("ExteriorWall")) continue;
                            Add(x, row.Height, z, f.Yaw, true, false, Near(FurnitureCatalog.Footprint(name, x, z, f.Yaw), f, u));
                        }
                }
                else
                {
                    // standing: against a face (a lean piece, a stack by the wall) or out in the yard, or on a porch's deck
                    float[] outs = row.Mount == DoodadMount.Lean ? new[] { 0.02f } : row.AgainstWall ? new[] { 0.05f } : new[] { 0.05f, 0.4f, 0.9f, 1.5f, 2.3f, 3.2f };
                    if (name == "Garden_Stepping_Stones_0") outs = Array.Empty<float>();
                    foreach (var f in Faces)
                    {
                        // (a house's cardboard by its garage: the kit's "garage" zone)
                        if (name == "Bound_Cardboard_Stack_0" && _res.Kind == BuildingKind.Residential && f.Inside.Kind != RoomKind.Garage) continue;
                        foreach (float sOut in outs)
                            for (float u = 0.3f; u <= f.Len - 0.3f + 1e-3f; u += 0.5f)
                            {
                                var yaws = row.Yaw == DoodadYaw.Any ? new List<float> { f.Yaw, (f.Yaw + 90f) % 360f, (f.Yaw + 180f) % 360f, (f.Yaw + 270f) % 360f } : new List<float> { f.Yaw };
                                if (row.Yaw == DoodadYaw.Any) rng.Shuffle(yaws);
                                foreach (float yaw in yaws)
                                {
                                    var fp0 = FurnitureCatalog.Footprint(name, 0f, 0f, yaw);
                                    // its near edge sOut off the face, its middle at u along it
                                    float lo = MathF.Abs(f.Nx) > 0.5f ? (f.Nx > 0 ? fp0.X0 : -fp0.X1) : (f.Nz > 0 ? fp0.Z0 : -fp0.Z1);
                                    float mid = MathF.Abs(f.Nx) > 0.5f ? (fp0.Z0 + fp0.Z1) * 0.5f * f.Dz : (fp0.X0 + fp0.X1) * 0.5f * f.Dx;
                                    var (x, z) = f.At(u - mid, sOut - lo);
                                    var fp = FurnitureCatalog.Footprint(name, x, z, yaw);
                                    bool onDeck = _decks.Any(d => Overlaps(fp, d.Box));
                                    Add(x, onDeck ? 0f : YardGround, z, yaw, false, false, Near(fp, f, u) + Side(f) - 0.3 * MathF.Abs(sOut - 1.2f) * (row.Mount == DoodadMount.Lean ? 0 : 1));
                                }
                            }
                    }
                    // a porch's deck, for a piece the kit allows on one
                    if (porch && row.Mount != DoodadMount.Lean)
                        foreach (var d in _decks)
                            for (float x = d.Box.X0 + 0.3f; x <= d.Box.X1 - 0.3f + 1e-3f; x += 0.4f)
                                for (float z = d.Box.Z0 + 0.3f; z <= d.Box.Z1 - 0.3f + 1e-3f; z += 0.4f)
                                    foreach (float yaw in new[] { 0f, 90f, 180f, 270f })
                                        Add(x, 0f, z, yaw, false, false, Near(FurnitureCatalog.Footprint(name, x, z, yaw), d.Face, 0f) + 1);
                    // stepping stones: a path straight out from a door to outside, from just past its sill or the porch's edge
                    if (name == "Garden_Stepping_Stones_0")
                        foreach (var f in Faces)
                            foreach (var o in f.W.Openings.Where(o => o.V < 0.05f && o.Archetype != ArchGarage))
                            {
                                float u = (o.U + o.U1) * 0.5f;
                                var (mx, mz) = f.At(u, 0.5f);
                                var deck = _decks.FirstOrDefault(d => Inside(d.Box, mx, mz));
                                float start = deck != null ? deck.Depth + 0.15f : 0.6f;
                                var (x, z) = f.At(u, start - s.Y0);
                                var door = _doors.Count == 0 ? default : _doors.OrderBy(q => MathF.Abs(q.X - mx) + MathF.Abs(q.Z - mz)).First();
                                Add(x, YardGround, z, f.Yaw, false, false, door.Role == 2 ? 3 : door.Role == 1 ? 1 : 0);
                            }
                }
                foreach (var (m, _) in cands.OrderByDescending(c => c.Score))
                    if (Fits(row, m)) return m;
                return null;
            }

            /// <summary>Does a piece go here: off the building and the posts and the chimney, in the yard (within YardReach of
            /// the walls), off the walks (a stepping stone is the walk), on a porch's deck wholly or off it by 0.3 m (as its
            /// row allows), its row's Spacing off what the yard holds and its ClearFront clear before it, not tall against a
            /// window's glass; hung on a wall: off the windows by DecorWindowGap at any height, the doorways by DecorOpenGap,
            /// another hung piece by DecorGap, the house's corners by DecorEnd.</summary>
            bool Fits(DoodadRow row, FurniturePlan m)
            {
                var s = FurnitureCatalog.Sizes[m.Name];
                var fp = m.Footprint;
                bool stones = m.Name == "Garden_Stepping_Stones_0", porch = row.Rooms.Contains("Porch");
                // (a piece hung on a wall or leant on it is at its face; one standing free keeps 5 cm off)
                float off = m.Mounted || row.Mount == DoodadMount.Lean ? 0f : 0.05f;
                if (_solid.Any(b => Overlaps(fp, Grow(b, off)))) return false;
                if (Gap(fp, _box) > YardReach) return false;
                if (m.Mounted)
                {
                    var f = Faces.FirstOrDefault(q => MathF.Abs((m.X - q.W.X) * q.Nx + (m.Z - q.W.Z) * q.Nz - q.T - DecorWallGap + s.Y0) < 0.05f
                                                       && (m.X - q.W.X) * q.Dx + (m.Z - q.W.Z) * q.Dz is var u && u > 0f && u < q.Len);
                    if (f == null) return false;
                    float um = (m.X - f.W.X) * f.Dx + (m.Z - f.W.Z) * f.Dz, a = um + s.X0, b = um + s.X1;
                    if (a < DecorEnd || b > f.Len - DecorEnd) return false;
                    float bottom = m.Y - s.H, top = m.Y + s.H;
                    foreach (var o in f.W.Openings)
                    {
                        bool window = o.V >= 0.05f;
                        float gap = window ? DecorWindowGap : DecorOpenGap;
                        if (!window && (o.V > top || o.V + o.Height < bottom)) continue;
                        if (a < o.U1 + gap && b > o.U - gap) return false;
                    }
                    return !_placed.Any(p => p.M.Mounted && Gap(fp, p.M.Footprint) < DecorGap);
                }
                var deck = _decks.FirstOrDefault(d => Overlaps(fp, Grow(d.Box, 0.3f)));
                if (deck != null)
                {
                    bool onIt = Within(fp, deck.Box, 0.05f);
                    if (m.Ceiling) { if (!onIt) return false; }
                    else if (!porch || !onIt || MathF.Abs(m.Y) > 0.01f) return false;
                    if (deck.Walks.Any(w => Overlaps(fp, w))) return false;
                }
                else if (m.Ceiling) return false;
                if (!stones && !m.Ceiling && _walks.Any(w => Overlaps(fp, w))) return false;
                foreach (var (o, r) in _placed)
                {
                    if (o.Mounted || o.Ceiling != m.Ceiling) continue;
                    if (Gap(fp, o.Footprint) < MathF.Max(row.Spacing, r.Spacing) - 1e-3f) return false;
                }
                if (row.ClearFront > 0f && !m.Ceiling)
                {
                    var (c, sn) = PlanTrig.CosSin(m.Yaw);
                    float fx = -sn, fz = -c, rx = c, rz = -sn;
                    float ax = m.X + rx * s.X0 + fx * s.Y1, az = m.Z + rz * s.X0 + fz * s.Y1, bx = m.X + rx * s.X1 + fx * (s.Y1 + row.ClearFront), bz = m.Z + rz * s.X1 + fz * (s.Y1 + row.ClearFront);
                    var zone = (MathF.Min(ax, bx), MathF.Min(az, bz), MathF.Max(ax, bx), MathF.Max(az, bz));
                    if (_solid.Any(b => Overlaps(zone, b)) || _placed.Any(p => !p.M.Mounted && !p.M.Ceiling && Overlaps(zone, p.M.Footprint))) return false;
                    if (deck == null && _decks.Any(d => Overlaps(zone, d.Box))) return false;
                }
                // nothing taller than a sill against a window's glass (0.6 m out, 0.3 either side of it)
                if (!m.Ceiling && m.Y + s.H > 0f)
                    foreach (var (x, z, sill, u0, u1, f) in _windows)
                    {
                        if (m.Y + s.H <= sill - 0.02f) continue;
                        var a = f.At(u0 - 0.3f, 0f); var b = f.At(u1 + 0.3f, 0.6f);
                        if (Overlaps(fp, (MathF.Min(a.X, b.X), MathF.Min(a.Z, b.Z), MathF.Max(a.X, b.X), MathF.Max(a.Z, b.Z)))) return false;
                    }
                return true;
            }
        }

        /// <summary>The yaw whose front is (fx, fz) -- Furnisher.YawFacing, for the yard.</summary>
        static float YardYaw(float fx, float fz) => MathF.Round((MathF.Atan2(-fx, -fz) * 180f / MathF.PI + 360f) % 360f * 1000f) / 1000f % 360f;
    }
